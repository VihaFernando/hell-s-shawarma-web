// Runs after `vite build` (see package.json). Writes the SEO/hosting files that
// depend on live blog data into the Netlify publish directory:
//   sitemap.xml, blog/rss.xml, _redirects, _headers, 404.html

import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { fetchPublishedBlog } from "./blog-data.mjs";

const SITE_URL = "https://hellsshawarma.lk";
const OUT = path.resolve("dist/client");

if (!process.env.VITE_SUPABASE_URL && existsSync(".env")) process.loadEnvFile(".env");

const esc = (s = "") =>
  String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
const abs = (p) => new URL(p, SITE_URL).toString();
const day = (iso) => (iso ? new Date(iso).toISOString().slice(0, 10) : undefined);
const latest = (dates) => dates.filter(Boolean).sort().at(-1);
// Same rule as postModifiedAt() in src/lib/blog/seo.ts.
const modifiedAt = (p) => latest([p.updated_at, p.published_at]);

// Same rule as src/lib/blog/images.ts ogImage(): Cloudinary gets a 1200px JPEG.
function shareImage(url) {
  if (!url) return null;
  if (!url.includes("res.cloudinary.com") || !url.includes("/image/upload/")) return url;
  const [head, tail] = url.split("/image/upload/");
  return `${head}/image/upload/f_jpg,q_auto,w_1200,c_limit/${tail.replace(/^([a-z]{1,3}_[^/]+)\//, "")}`;
}

function sitemap(data) {
  const posts = data?.posts.filter((p) => !p.noindex && !p.canonical_url) ?? [];
  const newest = latest(posts.map(modifiedAt));
  const urls = [
    { loc: "/" },
    { loc: "/menu" },
    { loc: "/gallery" },
    // /blog is noindex while it has no posts, so it only belongs in the sitemap once it has some.
    ...(posts.length ? [{ loc: "/blog", lastmod: newest }] : []),
    ...(data?.categories ?? [])
      .map((c) => {
        const inCat = posts.filter((p) => p.category?.slug === c.slug);
        return inCat.length
          ? {
              loc: `/blog/category/${c.slug}`,
              lastmod: latest([c.updated_at, ...inCat.map(modifiedAt)]),
            }
          : null;
      })
      .filter(Boolean),
    ...posts.map((p) => ({
      loc: `/blog/${p.slug}`,
      lastmod: modifiedAt(p),
      image: p.cover_image_url
        ? { loc: shareImage(p.cover_image_url), title: p.cover_image_alt || p.title }
        : null,
    })),
  ];

  const body = urls
    .map((u) =>
      [
        "  <url>",
        `    <loc>${esc(abs(u.loc))}</loc>`,
        u.lastmod ? `    <lastmod>${day(u.lastmod)}</lastmod>` : null,
        u.image
          ? `    <image:image>\n      <image:loc>${esc(u.image.loc)}</image:loc>\n    </image:image>`
          : null,
        "  </url>",
      ]
        .filter(Boolean)
        .join("\n"),
    )
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${body}
</urlset>
`;
}

function rss(data) {
  const posts = (data?.posts ?? []).filter((p) => !p.noindex).slice(0, 30);
  const items = posts
    .map((p) => {
      const link = abs(`/blog/${p.slug}`);
      const img = shareImage(p.cover_image_url);
      return `    <item>
      <title>${esc(p.title)}</title>
      <link>${esc(link)}</link>
      <guid isPermaLink="true">${esc(link)}</guid>
      <pubDate>${new Date(p.published_at).toUTCString()}</pubDate>
      <description>${esc(p.excerpt)}</description>${p.category ? `\n      <category>${esc(p.category.name)}</category>` : ""}${img ? `\n      <media:content url="${esc(img)}" medium="image" />` : ""}
    </item>`;
    })
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:media="http://search.yahoo.com/mrss/">
  <channel>
    <title>Hell's Shawarma Blog</title>
    <link>${abs("/blog")}</link>
    <description>Shawarma stories, Middle Eastern food culture, kitchen secrets and guides to every Hell's Shawarma branch in Colombo, Sri Lanka.</description>
    <language>en</language>
    <atom:link href="${abs("/blog/rss.xml")}" rel="self" type="application/rss+xml" />
    <image>
      <url>${abs("/apple-touch-icon.png")}</url>
      <title>Hell's Shawarma Blog</title>
      <link>${abs("/blog")}</link>
    </image>${posts[0] ? `\n    <lastBuildDate>${new Date(latest(posts.map(modifiedAt))).toUTCString()}</lastBuildDate>` : ""}
${items}
  </channel>
</rss>
`;
}

function redirects(data) {
  const lines = [
    "# Generated by scripts/blog-postbuild.mjs",
    // Renamed posts keep their rankings and inbound links.
    ...(data?.redirects ?? []).map((r) => `/blog/${r.from}  /blog/${r.to}  301`),
    "/blog/page/1  /blog  301",
    "/blog/category/:category/page/1  /blog/category/:category  301",
    // Admin is client-rendered from the SPA shell.
    "/admin  /_shell.html  200",
    "/admin/*  /_shell.html  200",
  ];
  return lines.join("\n") + "\n";
}

// CSP ships as Report-Only first: check the browser console for violations
// (GTM, embeds, Cloudinary, Supabase) on a deploy preview, then rename the header
// to Content-Security-Policy to enforce it.
const CSP = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://www.googletagmanager.com https://www.google-analytics.com",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  "connect-src 'self' https://*.supabase.co https://api.cloudinary.com https://*.google-analytics.com https://*.analytics.google.com https://www.googletagmanager.com",
  "frame-src https://www.google.com https://www.youtube.com https://www.youtube-nocookie.com https://player.vimeo.com https://www.instagram.com https://www.tiktok.com",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

const HEADERS = `# Generated by scripts/blog-postbuild.mjs
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy-Report-Only: ${CSP}
/admin
  X-Robots-Tag: noindex, nofollow
/admin/*
  X-Robots-Tag: noindex, nofollow
/_shell.html
  X-Robots-Tag: noindex, nofollow
/assets/*
  Cache-Control: public, max-age=31536000, immutable
/blog/rss.xml
  Content-Type: application/rss+xml; charset=utf-8
`;

const data = await fetchPublishedBlog();

mkdirSync(path.join(OUT, "blog"), { recursive: true });
writeFileSync(path.join(OUT, "sitemap.xml"), sitemap(data));
writeFileSync(path.join(OUT, "blog", "rss.xml"), rss(data));
writeFileSync(path.join(OUT, "_redirects"), redirects(data));
writeFileSync(path.join(OUT, "_headers"), HEADERS);
// Netlify serves 404.html with a 404 status; the shell lets the router render the branded not-found page.
if (existsSync(path.join(OUT, "_shell.html"))) {
  copyFileSync(path.join(OUT, "_shell.html"), path.join(OUT, "404.html"));
}

console.log(
  `[blog] postbuild: ${data?.posts.length ?? 0} posts, ${data?.redirects.length ?? 0} redirects -> sitemap.xml, blog/rss.xml, _redirects, _headers, 404.html`,
);
